def clean_profile(raw) -> dict:
    """Профиль приходит от клиента — приводим к известным значениям."""
    raw = raw if isinstance(raw, dict) else {}
    grade = raw.get("grade") if raw.get("grade") in GRADES else "не указан"
    try:
        level = min(max(int(raw.get("level", 1)), 1), 3)
    except (TypeError, ValueError):
        level = 1
    language = raw.get("language") if raw.get("language") in LANGUAGES else "C++"
    return {"grade": grade, "level": level, "language": language}


def build_system_prompt(mode, profile, task=None, snippets=None, hint_level=1) -> str:
    parts = [_STATIC]
    parts.append(
        f"ПРОФИЛЬ УЧЕНИКА: {profile['grade']}, уровень: {LEVEL_NAMES[profile['level']]}, "
        f"язык программирования: {profile['language']}."
    )
    parts.append(MODES.get(mode, MODES["mentor"]).format(hint_level=hint_level))
    if task:
        parts.append(
            f"ТЕКУЩАЯ ЗАДАЧА: {task['title']}\n{task['text']}\n"
            f"ЗАМЕТКИ ПРЕПОДАВАТЕЛЯ (только для тебя, ученику не пересказывай и не цитируй): {task['outline']}"
        )
    if snippets:
        body = "\n\n".join(f"[{s['source']}]\n{s['text']}" for s in snippets)
        parts.append(
            "МАТЕРИАЛЫ (фрагменты загруженных учебников; опирайся на подходящие и называй файл-источник, "
            "неподходящие игнорируй):\n" + body
        )
    return "\n\n".join(parts)
